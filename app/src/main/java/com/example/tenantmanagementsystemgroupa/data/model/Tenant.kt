package com.example.tenantmanagementsystemgroupa.data.model

import androidx.room.Entity
import androidx.room.PrimaryKey
import java.io.Serializable

/**
 * Domain entity representing a tenant lease record.
 * Annotated with @Entity for Jetpack Room persistence.
 * Implements Serializable to enable cross-component and Safe Args bundle passing.
 */
@Entity(tableName = "tenants")
data class Tenant(
    @PrimaryKey(autoGenerate = true)
    val id: Int = 0,
    val name: String,
    val phone: String,
    val rent: Double,
    val propertyUnit: String = "Apartment 101"
) : Serializable {

    /**
     * University Rubric Criterion:
     * Generates a comprehensive plain-text summary of tenant details
     * for implicit sharing via Intent.ACTION_SEND (WhatsApp, Messages, Gmail).
     */
    fun summary(): String {
        return StringBuilder()
            .append("=== TENANT LEASE SUMMARY ===\n")
            .append("Tenant ID: #$id\n")
            .append("Full Name: $name\n")
            .append("Contact Phone: $phone\n")
            .append("Property Unit: $propertyUnit\n")
            .append("Monthly Rent: KES %,.2f\n".format(rent))
            .append("Status: Active Lease Agreement\n")
            .append("Generated by: Tenant Management System")
            .toString()
    }
}
